function initialLang() {
    try {
        const saved = localStorage.getItem('agora.lang');
        if (saved && dict[saved]) return saved;
    } catch { /* sin storage */ }
    return (navigator.language || 'es').startsWith('es') ? 'es' : 'en';
}

export let lang = initialLang();
document.documentElement.lang = lang;

export function setLang(l) {
    lang = l;
    try { localStorage.setItem('agora.lang', l); } catch { /* sin storage */ }
    document.documentElement.lang = l;
}

export function t(key, vars) {
    let s = dict[lang][key] ?? dict.es[key] ?? key;
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, v);
    return s;
}
